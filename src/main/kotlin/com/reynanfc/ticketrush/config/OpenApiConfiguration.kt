package com.reynanfc.ticketrush.config

import io.swagger.v3.oas.models.OpenAPI
import io.swagger.v3.oas.models.info.Info
import org.springframework.context.annotation.Bean
import org.springframework.context.annotation.Configuration

// General information shown at the top of Swagger UI (/swagger-ui.html). Each controller documents itself.
@Configuration
class OpenApiConfiguration {

    @Bean
    fun openApi(): OpenAPI = OpenAPI().info(
        Info()
            .title("TicketRush API")
            .version("v1")
            .description(
                """
Ticket sales platform.

Conventions:
- money is always in cents (`Long`): R$ 150,00 is `15000`;
- timestamps are ISO-8601 in UTC (e.g. `2027-03-20T23:00:00Z`);
- ids are UUIDs generated by the server;
- errors have `timestamp`, `status`, `error`, `message` and `path`; validation errors (400) also list `fieldErrors`.
""".trimIndent(),
            ),
    )
}
