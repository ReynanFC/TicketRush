// OpenAPI documentation of EventController. Kept apart so the controller only shows HTTP wiring.
// Error bodies are produced by CatalogExceptionHandler: ValidationErrorResponseDTO (400) and ErrorResponseDTO (404, 422).
@Tag(
    name = "Events",
    description = "Catalog management: create an event, add sectors and lots, then publish it. " +
        "An event is only editable while DRAFT; after publishing it becomes read-only.",
)
interface EventControllerDocs {

    @Operation(
        summary = "Create an event",
        description = """
Creates a new event in **DRAFT** status, with no sectors.

The event id is generated by the server and returned in the body and in the `Location` header.

Next steps: add sectors (`POST /events/{eventId}/sectors`), add lots to each sector
(`POST /events/{eventId}/sectors/{sectorId}/lots`) and publish (`POST /events/{eventId}/publish`).

Timestamps are ISO-8601 in UTC (e.g. `2027-03-20T23:00:00Z`).""",
    )
    @ApiResponse(
        responseCode = "201",
        description = "Event created in DRAFT status.",
        headers = [Header(name = "Location", description = "URL of the new event: `/events/{id}`")],
    )
    @ApiResponse(
        responseCode = "400",
        description = "Invalid body: missing or blank fields, text too long, `startsAt` in the past or malformed JSON.",
        content = [Content(
            mediaType = JSON,
            schema = Schema(implementation = ValidationErrorResponseDTO::class),
            examples = [ExampleObject(name = "Validation error", value = VALIDATION_ERROR_EXAMPLE)],
        )],
    )
    fun createEvent(request: CreateEventRequestDTO): ResponseEntity<EventResponseDTO>

    @Operation(
        summary = "Add a sector to an event",
        description = """
Adds a sector (e.g. "Pista", "Camarote") to an event.

Rules:
- the event must be **DRAFT**;
- the sector name must be unique inside the event (comparison is case-sensitive).

The sector starts with no lots. An event can only be published when every sector has at least one lot.""",
    )
    @ApiResponse(
        responseCode = "201",
        description = "Sector added.",
        headers = [Header(name = "Location", description = "URL of the new sector: `/events/{eventId}/sectors/{sectorId}`")],
    )
    @ApiResponse(
        responseCode = "400",
        description = "Invalid body: blank name, name longer than 100 characters or malformed JSON.",
        content = [Content(
            mediaType = JSON,
            schema = Schema(implementation = ValidationErrorResponseDTO::class),
            examples = [ExampleObject(name = "Validation error", value = VALIDATION_ERROR_EXAMPLE)],
        )],
    )
    @ApiResponse(
        responseCode = "404",
        description = "Event not found.",
        content = [Content(
            mediaType = JSON,
            schema = Schema(implementation = ErrorResponseDTO::class),
            examples = [ExampleObject(name = "Event not found", value = EVENT_NOT_FOUND_EXAMPLE)],
        )],
    )
    @ApiResponse(
        responseCode = "422",
        description = "Business rule violated: the event is not DRAFT or the sector name is already in use.",
        content = [Content(
            mediaType = JSON,
            schema = Schema(implementation = ErrorResponseDTO::class),
            examples = [
                ExampleObject(name = "Event not in DRAFT", value = EVENT_NOT_IN_DRAFT_EXAMPLE),
                ExampleObject(name = "Duplicate sector name", value = DUPLICATE_SECTOR_NAME_EXAMPLE),
            ],
        )],
    )
    fun addSector(
        @Parameter(description = "Id of the event that receives the sector.", example = EVENT_ID)
        eventId: UUID,
        request: AddSectorRequestDTO,
    ): ResponseEntity<SectorResponseDTO>

    @Operation(
        summary = "Add a lot to a sector",
        description = """
Adds a ticket lot (e.g. "1º lote", "Meia-entrada") to a sector of the event.

Rules:
- the event must be **DRAFT**;
- the sector must belong to the event;
- `sortOrder` must be unique inside the sector (it defines the order lots are shown and sold);
- the sale window is half-open, `[startsAt, endsAt)`: a lot is on sale from `startsAt` (inclusive) until `endsAt` (exclusive);
- `endsAt` must be after `startsAt`;
- the window must not overlap the window of another lot in the same sector.
  Back-to-back windows are allowed: a lot may start exactly when the previous one ends.

`priceCents` is the price in cents: R$ 150,00 is `15000`.""",
    )
    @ApiResponse(
        responseCode = "201",
        description = "Lot added.",
        headers = [Header(name = "Location", description = "URL of the new lot: `/events/{eventId}/sectors/{sectorId}/lots/{lotId}`")],
    )
    @ApiResponse(
        responseCode = "400",
        description = "Invalid body: blank name, negative price, quantity not positive, `endsAt` in the past, " +
            "`endsAt` not after `startsAt` or malformed JSON.",
        content = [Content(
            mediaType = JSON,
            schema = Schema(implementation = ValidationErrorResponseDTO::class),
            examples = [ExampleObject(name = "Validation error", value = VALIDATION_ERROR_EXAMPLE)],
        )],
    )
    @ApiResponse(
        responseCode = "404",
        description = "Event not found, or the sector does not belong to the event.",
        content = [Content(
            mediaType = JSON,
            schema = Schema(implementation = ErrorResponseDTO::class),
            examples = [
                ExampleObject(name = "Event not found", value = EVENT_NOT_FOUND_EXAMPLE),
                ExampleObject(name = "Sector not found", value = SECTOR_NOT_FOUND_EXAMPLE),
            ],
        )],
    )
    @ApiResponse(
        responseCode = "422",
        description = "Business rule violated: the event is not DRAFT, the `sortOrder` is already in use " +
            "or the sale window overlaps another lot.",
        content = [Content(
            mediaType = JSON,
            schema = Schema(implementation = ErrorResponseDTO::class),
            examples = [
                ExampleObject(name = "Event not in DRAFT", value = EVENT_NOT_IN_DRAFT_EXAMPLE),
                ExampleObject(name = "Duplicate sort order", value = DUPLICATE_SORT_ORDER_EXAMPLE),
                ExampleObject(name = "Overlapping sale window", value = OVERLAPPING_WINDOW_EXAMPLE),
            ],
        )],
    )
    fun addLot(
        @Parameter(description = "Id of the event.", example = EVENT_ID)
        eventId: UUID,
        @Parameter(description = "Id of the sector that receives the lot. Must belong to the event.", example = SECTOR_ID)
        sectorId: UUID,
        request: AddLotRequestDTO,
    ): ResponseEntity<LotResponseDTO>

    @Operation(
        summary = "Publish an event",
        description = """
Moves the event from **DRAFT** to **PUBLISHED**. No request body.

Rules:
- the event must be **DRAFT** (publishing twice fails);
- the event must have at least one sector;
- every sector must have at least one lot.

After publishing, sectors and lots can no longer be added.""",
    )
    @ApiResponse(responseCode = "200", description = "Event published. The body is the event with status PUBLISHED.")
    @ApiResponse(
        responseCode = "404",
        description = "Event not found.",
        content = [Content(
            mediaType = JSON,
            schema = Schema(implementation = ErrorResponseDTO::class),
            examples = [ExampleObject(name = "Event not found", value = EVENT_NOT_FOUND_EXAMPLE)],
        )],
    )
    @ApiResponse(
        responseCode = "422",
        description = "Business rule violated: the event is not DRAFT, has no sectors or has a sector without lots.",
        content = [Content(
            mediaType = JSON,
            schema = Schema(implementation = ErrorResponseDTO::class),
            examples = [
                ExampleObject(name = "Event not in DRAFT", value = EVENT_NOT_IN_DRAFT_EXAMPLE),
                ExampleObject(name = "Event without sectors", value = EVENT_HAS_NO_SECTORS_EXAMPLE),
                ExampleObject(name = "Sector without lots", value = SECTOR_HAS_NO_LOTS_EXAMPLE),
            ],
        )],
    )
    fun publishEvent(
        @Parameter(description = "Id of the event to publish.", example = EVENT_ID)
        eventId: UUID,
    ): ResponseEntity<EventResponseDTO>
}

